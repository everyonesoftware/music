using Microsoft.UI.Dispatching;
using Microsoft.UI.Xaml;
using Microsoft.UI.Xaml.Controls;
using Velopack;

namespace Music.App;
internal static class Program
{
    [STAThread]
    public static void Main()
    {
        // Install/uninstall hooks must exit before WinUI or application data opens.
        // Applying downloaded updates remains an explicit user action.
        VelopackApp.Build().SetAutoApplyOnStartup(false).Run();
        try
        {
            WinRT.ComWrappersSupport.InitializeComWrappers();
            Application.Start(callback =>
            {
                SynchronizationContext.SetSynchronizationContext(new DispatcherQueueSynchronizationContext(DispatcherQueue.GetForCurrentThread()));
                _ = new MusicApplication();
            });
        }
        catch (Exception exception)
        {
            StartupDiagnostics.Write(exception, Environment.GetEnvironmentVariable("MUSIC_STARTUP_DIAGNOSTICS"));
            throw;
        }
    }
}

public sealed partial class MusicApplication : Application, Microsoft.UI.Xaml.Markup.IXamlMetadataProvider
{
    // Normally generated by XamlCompiler. Runtime XAML still needs the real
    // WinUI metadata provider for controls and their default templates.
    private readonly Microsoft.UI.Xaml.XamlTypeInfo.XamlControlsXamlMetaDataProvider metadata = new();
    public Microsoft.UI.Xaml.Markup.IXamlType GetXamlType(Type type) => metadata.GetXamlType(type);
    public Microsoft.UI.Xaml.Markup.IXamlType GetXamlType(string name) => metadata.GetXamlType(name);
    public Microsoft.UI.Xaml.Markup.XmlnsDefinition[] GetXmlnsDefinitions() => metadata.GetXmlnsDefinitions();
    private MainWindow? window;
    public MusicApplication()
    {
        UnhandledException += (_, args) => StartupDiagnostics.Write(args.Exception, Environment.GetEnvironmentVariable("MUSIC_STARTUP_DIAGNOSTICS"));
    }
    protected override void OnLaunched(LaunchActivatedEventArgs args)
    {
        // Application.Start invokes the constructor before the internal core application
        // exists. Runtime-XAML resources must wait until launch, before loading the shell.
        Resources.MergedDictionaries.Add(new XamlControlsResources());
        Resources["SystemAccentColor"] = Windows.UI.Color.FromArgb(255, 192, 215, 174);
        window = new MainWindow();
        window.Activate();
#if MUSIC_NATIVE_ACCEPTANCE
        if (NativeAcceptance.IsRequested)
        {
            window.DispatcherQueue.TryEnqueue(() => _ = window.RunNativeAcceptanceAsync());
            return;
        }
#endif
        _ = window.CheckForUpdatesOnStartupAsync();
    }
}
